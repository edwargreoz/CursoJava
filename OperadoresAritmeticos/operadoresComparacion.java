package OperadoresAritmeticos;

public class operadoresComparacion {

    public static void main(String[] args) {
        
        //operadores realciones o comparacion
        var a = 5;
        var b = 3;

        System.out.println(a == b);
        System.out.println(a == 6);
        System.out.println(a == 5);

        System.out.println(a != 6);
        System.out.println(a < b );
        System.out.println(a > b );
        System.out.println(a <= b );
        System.out.println(a >= b );

        
    }
    
}
