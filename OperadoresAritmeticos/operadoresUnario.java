package OperadoresAritmeticos;

public class operadoresUnario {
    public static void main(String[] args) {
        var a = 5;
        var b = 3;

        System.out.println(+b);
        System.out.println(-b);
        System.out.println(+a);
        System.out.println(-a);

        System.out.println("--------");
        

        System.out.println(++b);
        System.out.println(b++);
        System.out.println(b);
        System.out.println(++a);
        System.out.println(a++);
        System.out.println(a);

        System.out.println("--------");

        System.out.println(--b);
        System.out.println(b--);
        System.out.println(b);
        System.out.println(--a);
        System.out.println(a--);
        System.out.println(a);


        
        
        
    }
    
}
